"""Fake source for testing the pipeline end to end without touching real sites.

Listings are stable per (make, model, index) so re-runs update them rather than duplicating,
and prices drift a little between runs so price history gets exercised.
Set `options.mode` in sources.yaml to `blocked` or `error` to test degraded handling.
"""
from __future__ import annotations

import random
import time
from collections.abc import AsyncIterator

from carscout.normalise.mapping import normalise_make, normalise_model
from carscout.sources.base import (
    NormalisedListing,
    RawListing,
    SearchParams,
    SourceBlocked,
    SourcePlugin,
)
from carscout.sources.http import PoliteClient

_FALLBACK = [("Toyota", "Corolla"), ("Mazda", "3"), ("Hyundai", "i30"), ("Volkswagen", "Golf")]
_VARIANTS = ["Ascent Sport", "SX", "ZR", "Active", "Elite", "GT"]
_PLACES = [("Richmond", "VIC", "3121"), ("Parramatta", "NSW", "2150"), ("Fortitude Valley", "QLD", "4006"),
           ("Glenelg", "SA", "5045"), ("Fremantle", "WA", "6160"), ("Geelong", "VIC", "3220")]
_COLOURS = ["White", "Silver", "Grey", "Blue", "Red", "Black"]


class Plugin(SourcePlugin):
    name = "demo"
    needs_http = False

    async def search(self, params: SearchParams, http: PoliteClient) -> AsyncIterator[RawListing]:
        mode = self.config.options.get("mode", "ok")
        count = min(int(self.config.options.get("count", 12)), params.max_results)
        if mode == "blocked":
            raise SourceBlocked("demo: simulated bot protection")
        drift = random.Random(int(time.time() // 300))  # changes every 5 minutes

        y_min = params.year_min or 2012
        y_max = max(params.year_max or 2023, y_min)
        for i in range(count):
            if mode == "error" and i == 2:
                raise RuntimeError("demo: simulated parser crash after 2 listings")
            make, model = (params.make, params.model) if params.make else _FALLBACK[i % len(_FALLBACK)]
            model = model or _FALLBACK[i % len(_FALLBACK)][1]
            rnd = random.Random(f"{make}|{model}|{i}")
            year = rnd.randint(y_min, y_max)
            km_cap = params.km_max or 200_000
            km = rnd.randint(5_000, max(km_cap, 6_000))
            base = 38_000 - (2025 - year) * 2_100 - km // 20
            price = max(3_000, int(base * rnd.uniform(0.85, 1.15)))
            if drift.random() < 0.3:
                price -= drift.choice([500, 1_000, 1_500])
            suburb, state, postcode = rnd.choice(_PLACES)
            if params.states and state not in params.states:
                suburb, state, postcode = "Somewhere", params.states[0], None
            ident = f"{make}-{model}-{i}".lower().replace(" ", "-")
            yield RawListing(
                source_listing_id=ident,
                url=f"https://example.invalid/demo/{ident}",
                payload={
                    "id": ident, "make": make, "model": model,
                    "badge": rnd.choice(_VARIANTS), "year": year, "km": km,
                    "price": price, "priceType": rnd.choice(["DAP", "EGC", "Negotiable"]),
                    "body": "Hatch", "trans": rnd.choice(["Automatic", "Manual"]),
                    "fuel": "Petrol", "colour": rnd.choice(_COLOURS),
                    "seller": rnd.choice(["Dealer", "Private"]),
                    "suburb": suburb, "state": state, "postcode": postcode,
                },
            )

    def parse(self, raw: RawListing) -> NormalisedListing:
        p = raw.payload
        make = normalise_make(p["make"])
        model = normalise_model(make, p["model"])
        return NormalisedListing(
            source_listing_id=raw.source_listing_id,
            url=raw.url,
            title=f"{p['year']} {make} {model} {p['badge']}",
            make=make,
            model=model,
            variant=p["badge"],
            year=p["year"],
            odometer_km=p["km"],
            price=p["price"],
            price_type={"DAP": "drive_away", "EGC": "egc", "Negotiable": "negotiable"}.get(
                p["priceType"], "unknown"
            ),
            body_type=p["body"],
            transmission=p["trans"],
            fuel_type=p["fuel"],
            colour=p["colour"],
            seller_type=p["seller"].lower(),
            suburb=p["suburb"],
            state=p["state"],
            postcode=p["postcode"],
            description="Demo listing generated by CarScout. Not a real car.",
        )
